/**
 * Sync offline-transfer app tree from repository root.
 * Source of truth = root package. Does not copy node_modules or .next.
 *
 * Usage: bun run scripts/bundle-offline.ts
 */
import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const bundleRoot = join(root, "offline-transfer-postgresql-win10");
const appDest = join(bundleRoot, "app");

const COPY_DIRS = ["src", "drizzle", "public", "scripts", "docs", "tests", "test-support"] as const;
const COPY_FILES = [
  "package.json",
  "bun.lock",
  "tsconfig.json",
  "next.config.ts",
  "next-env.d.ts",
  "postcss.config.mjs",
  "eslint.config.mjs",
  "vitest.config.ts",
  "playwright.config.ts",
  "drizzle.config.ts",
  "README.md",
  "PRODUCT.md",
  "DESIGN.md",
  "AGENTS.md",
] as const;

function ensureDir(path: string) {
  mkdirSync(path, { recursive: true });
}

function copyDir(from: string, to: string) {
  if (!existsSync(from)) {
    console.warn(`[bundle-offline] skip missing dir: ${from}`);
    return;
  }
  cpSync(from, to, {
    recursive: true,
    filter: (source) => {
      const base = source.replace(/\\/g, "/");
      if (base.includes("/node_modules") || base.includes("/.next")) return false;
      if (base.endsWith("/coverage") || base.includes("/coverage/")) return false;
      if (base.includes("/test-results")) return false;
      return true;
    },
  });
}

function copyFile(name: string) {
  const from = join(root, name);
  if (!existsSync(from)) {
    console.warn(`[bundle-offline] skip missing file: ${name}`);
    return;
  }
  cpSync(from, join(appDest, name));
}

if (!existsSync(bundleRoot)) {
  console.error(`[bundle-offline] missing ${bundleRoot}`);
  process.exit(1);
}

/** Local-only paths operators keep across rebundles (never wipe). */
const PRESERVE_APP_ENTRIES = new Set([
  "node_modules",
  ".env",
  ".env.local",
  ".env.production",
  ".env.development",
]);

// Wipe previous app tree so orphans cannot stay stale; preserve node_modules + env secrets.
if (existsSync(appDest)) {
  const preserved: string[] = [];
  for (const entry of readdirSync(appDest)) {
    if (PRESERVE_APP_ENTRIES.has(entry)) {
      preserved.push(entry);
      continue;
    }
    rmSync(join(appDest, entry), { recursive: true, force: true });
  }
  if (preserved.length) {
    console.log(
      `[bundle-offline] cleared previous app/ (preserved: ${preserved.join(", ")})`,
    );
  } else {
    console.log("[bundle-offline] cleared previous app/");
  }
  if (!existsSync(join(appDest, "node_modules"))) {
    console.warn(
      "[bundle-offline] app/node_modules missing — after package.json/lock changes run: cd offline-transfer-postgresql-win10/app && bun install",
    );
  }
}
ensureDir(appDest);

for (const dir of COPY_DIRS) {
  copyDir(join(root, dir), join(appDest, dir));
  console.log(`[bundle-offline] synced ${dir}/`);
}

for (const file of COPY_FILES) {
  copyFile(file);
  console.log(`[bundle-offline] synced ${file}`);
}

const stamp = {
  builtAt: new Date().toISOString(),
  source: "root",
  note: "Generated by scripts/bundle-offline.ts — do not hand-edit app/ as source of truth",
};
writeFileSync(join(appDest, "BUNDLE-SYNC.json"), `${JSON.stringify(stamp, null, 2)}\n`, "utf8");
console.log("[bundle-offline] wrote BUNDLE-SYNC.json");
console.log("[bundle-offline] done. Run production build inside bundle when packaging.");
